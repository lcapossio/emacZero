// gthe4_channel_10g.v - One GTHE4 transceiver channel set up for 10GBASE-R
// (10.3125 Gb/s) in raw mode, for the emacZero 10G PCS (rtl/pcs10gbr.v).
//
// The primitive is instantiated directly (no Transceiver Wizard IP):
//   - clocked from QPLL0 of the quad's GTHE4_COMMON (gthe4_common_10g.v),
//     half-rate 5.15625 GHz, TXOUT_DIV = RXOUT_DIV = 1
//   - 64-bit TXDATA / RXDATA with a 32-bit internal datapath, 8b10b and the
//     GT's own 64b66b gearbox off: the PCS does its own 64b/66b gearing
//   - TXUSRCLK = RXUSRCLK = 322.27 MHz, TXUSRCLK2 = RXUSRCLK2 = 161.13 MHz,
//     made by BUFG_GTs from TXOUTCLK / RXOUTCLK (PROGDIV by 16 of the
//     PLL clock, TX/RXOUTCLKSEL = 3'b101); the user logic owns those buffers
//   - TX and RX elastic buffers on, TX/RX phase aligners bypassed, RX clock
//     correction off (the RX side runs on the recovered clock)
//   - DFE receiver by default (rxlpmen = 0); LPM selectable at run time
//   - TXDATA[0] / RXDATA[0] are the first bits on the line
//
// Every attribute that differs from the UNISIM default is set below, grouped
// by function; the values were cross-checked against a scratch Transceiver
// Wizard reference configuration (10.3125 Gb/s raw, 156.25 MHz QPLL0
// reference) that is not part of this repository. Every primitive input is
// tied explicitly; outputs not used are left open.
//
// LOOPBACK: 3'b000 normal, 3'b001 near-end PCS, 3'b010 near-end PMA,
// 3'b100 far-end PMA, 3'b110 far-end PCS. Pulse GTRXRESET after a change.
// Verilog 2001
// =============================================================================

